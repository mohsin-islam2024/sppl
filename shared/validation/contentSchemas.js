import { z } from "zod";
import {
  objectId,
  slug,
  createNewsSchema,
  createGallerySchema,
  createSponsorSchema,
  createAwardSchema,
  createAnnouncementSchema,
  createVideoSchema,
} from "./schemas.js";

/**
 * Admin-side schemas for the content manager (news, gallery, sponsors, awards,
 * announcements).
 *
 * They extend the base create schemas rather than replacing them, so the public
 * contract stays in one place. What the extension adds:
 *
 *   - the fields the models already have but the base schemas dropped (zod strips
 *     unknown keys, so `statValue`, `address`, `thumbnailUrl` could never be saved);
 *   - `nullable()` on optional references and dates, so an admin can CLEAR a match,
 *     a winner or an expiry date on edit instead of being stuck with the old value;
 *   - an optional news `slug`, generated by the server from the English title.
 *
 * Update schemas are partial and never allow `seasonId` — moving a record to
 * another season is a delete-and-recreate, not an edit.
 */

const nullableId = objectId.nullable().optional();

/* News */
export const adminCreateNewsSchema = createNewsSchema.extend({
  slug: slug.optional(),
  coverPublicId: z.string().trim().max(200).optional(),
});
export const adminUpdateNewsSchema = adminCreateNewsSchema
  .partial()
  .omit({ seasonId: true });

/* Gallery */
export const adminCreateGallerySchema = createGallerySchema.extend({
  matchId: nullableId,
  thumbnailUrl: z.string().trim().max(500).optional(),
  width: z.coerce.number().int().positive().optional(),
  height: z.coerce.number().int().positive().optional(),
  // Lets an admin hide a photo without deleting it.
  active: z.boolean().optional(),
});
export const adminUpdateGallerySchema = adminCreateGallerySchema
  .partial()
  .omit({ seasonId: true });

/* Sponsors */
export const adminCreateSponsorSchema = createSponsorSchema.extend({
  // The base rule rejects an empty string, which made it impossible to clear a phone.
  phone: z
    .string()
    .trim()
    .regex(/^(\+?[0-9\-\s]{6,20})?$/, "Invalid phone number")
    .optional(),
  address: z.string().trim().max(300).optional(),
});
export const adminUpdateSponsorSchema = adminCreateSponsorSchema
  .partial()
  .omit({ seasonId: true });

/* Awards */
export const adminCreateAwardSchema = createAwardSchema.extend({
  matchId: nullableId,
  winnerPlayerId: nullableId,
  winnerTeamId: nullableId,
  statValue: z.string().trim().max(100).optional(),
  isSquadWide: z.boolean().optional(),
});
export const adminUpdateAwardSchema = adminCreateAwardSchema
  .partial()
  .omit({ seasonId: true });

/* Announcements */
export const adminCreateAnnouncementSchema = createAnnouncementSchema.extend({
  expiresAt: z.coerce.date().nullable().optional(),
});
export const adminUpdateAnnouncementSchema = adminCreateAnnouncementSchema
  .partial()
  .omit({ seasonId: true });

/* Videos */
export const adminCreateVideoSchema = createVideoSchema.extend({
  // The provider and embed id are derived from the URL on the server, so a pasted
  // link is the only thing an admin has to get right. Anything sent here is ignored.
  provider: z.string().optional(),
  matchId: nullableId,
  published: z.boolean().optional(),
  order: z.coerce.number().int().min(0).max(9999).optional(),
  thumbnailUrl: z.string().trim().max(500).optional(),
});
export const adminUpdateVideoSchema = adminCreateVideoSchema
  .partial()
  .omit({ seasonId: true });
